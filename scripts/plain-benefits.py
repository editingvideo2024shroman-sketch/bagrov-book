def clean_take(s: str) -> str:
    for a, c in TAKE_FIX:
        s = re.sub(a, c, s)
    s = re.sub(r"\s+", " ", s)
    s = re.sub(r" \.", ".", s)
    s = s.replace("..", ".")
    return s.strip()


