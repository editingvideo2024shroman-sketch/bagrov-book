SKIP_WHY = re.compile(
    r"не ваш вариант|вот салат|аптек|зелёный стакан|третья чашка|"
    r"лимон и томат|баночка витаминов|магазинный майонез|"
    r"нормальная еда, не",
    re.I,
)


def clean_why(r):
    title = r["title"].rstrip(".")
    parts = [s.strip() for s in re.split(r"(?<=[.!?])\s+", r["why"].strip()) if s.strip()]
    keep = []
    for s in parts:
        if SKIP_WHY.search(s):
            continue
        if "—" in s:
            left, right = s.split("—", 1)
            # drop "вот салат / запечённая свёкла" tails
            if re.search(r"салат|свёкл|сок", right, re.I) and "туалет" not in left.lower():
                s = left.strip().rstrip(".") + "."
        keep.append(s if s.endswith((".", "!", "?")) else s + ".")
    if not keep:
        return title + "."
    # prefer starting with title if first kept sentence is close
    text = " ".join(keep)
    text = re.sub(r"\s+", " ", text).strip()
    text = re.sub(r"^(Если )у вас ", r"\1", text)
    text = re.sub(r"^(Если )вас ", r"\1", text)
    return text


def has(ing, *words):
    t = ing.lower()
    return any(w in t for w in words)


