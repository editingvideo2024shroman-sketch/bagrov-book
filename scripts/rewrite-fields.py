FLUFF_BEN = [
    "не аптека",
    "не таблетка",
    "не лекарство",
    "не ваш день",
    "уже не ваш",
    "не ваш вариант",
]


def clean_ben(s):
    parts = [x.strip() for x in re.split(r"(?<=[.!?])\s+", s.strip()) if x.strip()]
    keep = []
    for x in parts:
        xl = x.lower()
        if any(f in xl for f in FLUFF_BEN):
            continue
        keep.append(x if x.endswith((".", "!", "?")) else x + ".")
    return " ".join(keep) if keep else s


